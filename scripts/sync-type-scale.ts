#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TOKENS_PATH = join(ROOT, "Config", "TypeScale.json");
const SWIFT_PATH = join(ROOT, "Putio", "Common", "BrandTypography.swift");

const WEIGHTS: Readonly<Record<string, string>> = {
  regular: ".regular",
  medium: ".medium",
  bold: ".bold",
  black: ".black",
};
const FAMILIES = ["sans", "mono"];
const ANCHORS = [
  "largeTitle",
  "title1",
  "title2",
  "title3",
  "headline",
  "body",
  "callout",
  "subheadline",
  "footnote",
  "caption1",
  "caption2",
];

type Role = Readonly<Record<string, unknown>>;

function fetch(record: Readonly<Record<string, unknown>>, key: string): unknown {
  if (!Object.hasOwn(record, key)) throw new Error(`key not found: ${JSON.stringify(key)}`);
  return record[key];
}

export function formatNumber(value: unknown): string {
  if (typeof value === "string") return value;
  if (typeof value !== "number" || !Number.isFinite(value)) {
    throw new Error(`not a number: ${JSON.stringify(value)}`);
  }
  if (Number.isInteger(value)) return BigInt(value).toString();
  if (Math.abs(value) >= 1e-4) return String(value);
  const [mantissa = "", exponent = ""] = value.toExponential().split("e");
  const digits = mantissa.includes(".") ? mantissa : `${mantissa}.0`;
  const sign = exponent.startsWith("-") ? "-" : "+";
  return `${digits}e${sign}${exponent.replace(/^[+-]/, "").padStart(2, "0")}`;
}

function renderCase(role: Role): string {
  const name = String(fetch(role, "name"));
  const family = String(fetch(role, "family"));
  if (!FAMILIES.includes(family)) throw new Error(`unknown family ${family}`);

  const weight = fetch(WEIGHTS, String(fetch(role, "weight")));
  const anchor = String(fetch(role, "anchor"));
  if (!ANCHORS.includes(anchor)) throw new Error(`unknown anchor ${anchor}`);

  const line = formatNumber(fetch(role, "lineHeight"));
  const track = formatNumber(fetch(role, "tracking"));
  const uppercase = fetch(role, "uppercase");
  const upper = uppercase === false || uppercase === null ? "false" : "true";

  return (
    `        case .${name}:\n` +
    `            return ${family}(${weight}, .${anchor}, tracking: ${track}, lineHeight: ${line}, uppercase: ${upper}, traits: traits)`
  );
}

export function renderSwift(roles: readonly Role[]): string {
  const cases = roles.map((role) => `        case ${String(fetch(role, "name"))}`).join("\n");
  const resolvers = roles.map(renderCase).join("\n");

  return `// GENERATED by scripts/sync-type-scale.ts from Config/TypeScale.json. Do not edit.
//
// The design system's Type · Scale on the two brand families — GT America
// (sans) and Berkeley Mono (numerics and code) — scaled through
// UIFontMetrics. Every accessor returns nil when the licensed faces are
// absent, so callers keep their original font.
import UIKit

enum BrandTypography {
    enum Role {
${cases}
    }

    struct Style {
        let font: UIFont
        // Kerning in points at the resolved size (0 = none).
        let tracking: CGFloat
        let lineHeightMultiple: CGFloat
        let isUppercase: Bool
    }

    // Pass \`traits\` — a label's own trait collection — to keep tracking
    // and size in proportion at that content size category. Omit it to
    // resolve against the current environment.
    static func styleIfAvailable(_ role: Role, compatibleWith traits: UITraitCollection? = nil) -> Style? {
        switch role {
${resolvers}
        }
    }

    static func fontIfAvailable(_ role: Role) -> UIFont? {
        styleIfAvailable(role)?.font
    }

    private static func sans(_ weight: UIFont.Weight, _ anchor: UIFont.TextStyle,
                             tracking: CGFloat, lineHeight: CGFloat, uppercase: Bool,
                             traits: UITraitCollection?) -> Style? {
        guard let brand = BrandFont.sansIfAvailable(size: nativeSize(anchor), weight: weight) else { return nil }
        return make(brand, anchor, tracking: tracking, lineHeight: lineHeight, uppercase: uppercase, traits: traits)
    }

    private static func mono(_ weight: UIFont.Weight, _ anchor: UIFont.TextStyle,
                             tracking: CGFloat, lineHeight: CGFloat, uppercase: Bool,
                             traits: UITraitCollection?) -> Style? {
        guard let brand = BrandFont.monoIfAvailable(size: nativeSize(anchor), weight: weight) else { return nil }
        return make(brand, anchor, tracking: tracking, lineHeight: lineHeight, uppercase: uppercase, traits: traits)
    }

    // A role's base size is its anchor text style's native iOS size, which
    // is what lets UIFontMetrics scale it with the accessibility setting.
    private static func nativeSize(_ style: UIFont.TextStyle) -> CGFloat {
        UIFont.preferredFont(
            forTextStyle: style,
            compatibleWith: UITraitCollection(preferredContentSizeCategory: .large)
        ).pointSize
    }

    private static func make(_ brand: UIFont, _ anchor: UIFont.TextStyle,
                             tracking: CGFloat, lineHeight: CGFloat, uppercase: Bool,
                             traits: UITraitCollection?) -> Style {
        let scaled = UIFontMetrics(forTextStyle: anchor).scaledFont(for: brand, compatibleWith: traits)
        return Style(
            font: scaled,
            // Tracking is em; scaling by the resolved point size gives an
            // absolute kern that holds its proportion at any size.
            tracking: tracking * scaled.pointSize,
            lineHeightMultiple: lineHeight,
            isUppercase: uppercase
        )
    }
}
`;
}

function main(checkOnly: boolean): number {
  const parsed: unknown = JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
  const roles = fetch(parsed as Readonly<Record<string, unknown>>, "roles");
  if (!Array.isArray(roles)) throw new Error("roles must be an array");
  const swift = renderSwift(roles as Role[]);

  if (checkOnly) {
    const current = existsSync(SWIFT_PATH) ? readFileSync(SWIFT_PATH) : Buffer.alloc(0);
    if (!current.equals(Buffer.from(swift, "utf8"))) {
      console.error("BrandTypography.swift is out of sync with Config/TypeScale.json. Run: mise run type-scale-sync");
      return 1;
    }
    console.log(`Verified ${roles.length} type-scale roles.`);
  } else {
    writeFileSync(SWIFT_PATH, swift);
    console.log(`Generated BrandTypography.swift (${roles.length} roles).`);
  }
  return 0;
}

if (import.meta.main) {
  try {
    process.exitCode = main(process.argv.slice(2).includes("--check"));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
